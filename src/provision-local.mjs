// provision-local.mjs — 用 cloudflared 自己的证书开通固定地址（本地管理型隧道）
//
// 为什么要有这条路：zone 级 API Token 不是谁手边都有，也不该为了一次开通就建一个。
// `cloudflared tunnel login` 会在本机写一份 zone 范围的 cert.pem；之后 create / route dns
// 都用它完成，全程不需要我们接触 API Token。
//
// 与 token 形态（cloudflare.mjs）的差别只有一个：cloudflared 用 `--config` 指向本地
// ingress 配置 + credentials 文件，而不是 `TUNNEL_TOKEN` 环境变量。对外接口保持一致：
//   ensure({ port }) → { hostname, url, tunnelId, created }
//   credential({ port }) → { hostname, configFile }
//
// 安全边界：
//   · cert.pem 属于 zone 级凭据，绝不复制、绝不外发；这里只检查它存在；
//   · credentials 文件同理，只把**路径**写进配置，不读内容、不进日志；
//   · 配置与状态文件都 0600。

import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFile as nodeExecFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fail } from './protocol.mjs';
import { deriveSubdomain, isValidLabel } from './dns-label.mjs';
import { dnsWarningFor, evaluateDnsAnswer, probeDns, resolveNs } from './dns-probe.mjs';
import { cnameBelongsTo, readZoneCert } from './zone-health.mjs';
import { findCloudflared } from './tunnel.mjs';

const execFileAsync = promisify(nodeExecFile);
const CLI_TIMEOUT_MS = 45_000;
const STATE_VERSION = 1;

const UUID_PATTERN = /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/i;

/**
 * 这条隧道是否还活着（未删除）。
 *
 * 坑：`cloudflared tunnel list --output json` 对**未删除**的隧道给的是 Go 的零值时间
 * `"deleted_at": "0001-01-01T00:00:00Z"`，既不是 null 也不是空串。所以 `!t.deleted_at`
 * 会把账号里每一条活隧道都判成已删除 —— 后果是「按名查找」永远落空，每次开通都去
 * create 然后撞 `tunnel with name already exists`（0.2.12 现场就是这个）。
 * 判定必须同时接受：字段缺失 / null / 空串 / 零值时间。
 */
function isLiveTunnel(t) {
  if (!t || !t.id) return false;
  const deleted = t.deleted_at;
  if (!deleted) return true;
  return String(deleted).startsWith('0001-01-01');
}

function readState(file, log) {
  if (!file) return null;
  try {
    const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!parsed || parsed.version !== STATE_VERSION) throw new Error('结构不符');
    return parsed;
  } catch (err) {
    if (err.code !== 'ENOENT') log?.(`tunnel 本地开通状态不可用：${err.message}`);
    return null;
  }
}

function writeState(file, state) {
  if (!file) return;
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify({ version: STATE_VERSION, ...state }, null, 2), { mode: 0o600, flag: 'w' });
  fs.renameSync(tmp, file);
  try { fs.chmodSync(file, 0o600); } catch { /* 刚写即 0600 */ }
}

/** cloudflared 的 ingress 配置文件。ports/hostname 变一次就要重写一次。 */
export function renderConfig({ tunnelId, credentialsFile, hostname, port }) {
  return [
    `# generated by dsh-mobile — 端口变化会重写本文件；不要手改`,
    `tunnel: ${tunnelId}`,
    `credentials-file: ${credentialsFile}`,
    '',
    'ingress:',
    `  - hostname: ${hostname}`,
    `    service: http://127.0.0.1:${port}`,
    '  - service: http_status:404',
    '',
  ].join('\n');
}

/**
 * zone 诊断结果的**展示副本**：只留结论与 NS 名字。
 *
 * zoneId / accountId 这类内部标识一律不落状态文件、不进面板——
 * 面板只需要知道「归谁、对不对」，不需要也不该拿到账号坐标。
 */
export function sanitizeZone(zone) {
  if (!zone || typeof zone !== 'object') return null;
  const list = (v) => (Array.isArray(v) ? v.map((x) => String(x).toLowerCase()).filter(Boolean).slice(0, 4) : []);
  return {
    code: zone.code || 'unknown',
    status: zone.status || null,
    expectedNs: list(zone.expectedNs),
    publicNs: list(zone.publicNs),
    zoneName: zone.zoneName || null,
    accountName: zone.accountName || null,
    checkedAt: new Date().toISOString(),
  };
}

export class LocalProvisioner {
  constructor({
    baseDomain = 'matrixboard.cn',
    prefix = 'dsh',
    executable = 'cloudflared',
    stateFile = null,
    configFile = null,
    seed = null,
    homeDir = os.homedir(),
    log = () => {},
    run = null,
    // 可注入：解析 cloudflared 时用的环境（PATH / HOME）。测试必须能隔离真实 PATH。
    env = process.env,
    // 可注入：测试里不该真发 DNS 查询（会等 NXDOMAIN 重试，还依赖外网）
    probe = null,
    // 可注入：解析失败时进一步问「这个域名现在归哪个 Cloudflare 账号」。
    // 不注入就不诊断（测试/离线场景保持零网络依赖）；生产由 createProvisioner 注入。
    zoneDiagnose = null,
    // 可注入：开通前查这条 hostname 现在指向哪条隧道，避免多机互相覆盖。
    ownerLookup = null,
  } = {}) {
    this.baseDomain = String(baseDomain).replace(/^\./, '').toLowerCase();
    this.prefix = prefix;
    this.executable = executable;
    this.stateFile = stateFile;
    this.configFile = configFile || path.join(path.dirname(stateFile || path.join(homeDir, 'x')), 'tunnel-config.yml');
    this.seed = seed;
    this.homeDir = homeDir;
    this.env = env;
    this.log = log;
    this._state = undefined;
    // 可注入，测试里不必真起 cloudflared
    this.run = run || this.#exec;
    this.probe = probe || probeDns;
    this.zoneDiagnose = zoneDiagnose;
    this.ownerLookup = ownerLookup;
    this._zone = null; // 最近一次 zone 诊断结论（不含凭据）
  }

  get kind() {
    return 'local';
  }

  get state() {
    if (this._state === undefined) this._state = readState(this.stateFile, this.log);
    return this._state;
  }

  get configured() {
    // 本地形态只要证书在就算可开通；已开通则要配置与凭据都在
    if (this.state?.configFile) return true;
    return fs.existsSync(path.join(this.homeDir, '.cloudflared', 'cert.pem'));
  }

  get notConfiguredMessage() {
    return '主机还没有登录 Cloudflare';
  }

  get notConfiguredDetail() {
    const exe = findCloudflared(this.executable, this.env) || findCloudflared('auto', this.env) || this.executable;
    return `在这台电脑的终端执行：${exe} tunnel login（浏览器里选 ${this.baseDomain} 授权）`;
  }

  /**
   * 安装完成后回填刚下载的可执行文件路径。
   *
   * 必要性：插件启动那一刻就决定了本实例用哪个 executable，而「自动安装」发生在启动
   * 之后。新机器（尤其 Windows）上 PATH 里没有 cloudflared，回填前开通会在
   * `execFile('cloudflared.exe')` 直接 ENOENT —— 用户看到的是「装好了但开通失败」。
   */
  useExecutable(executable) {
    if (executable) this.executable = executable;
  }

  /**
   * 解析本次真正要执行的 cloudflared。
   *
   * 用发现链而不是信任构造参数：安装落点（组件目录）并不在 PATH 里，裸名字在 Windows
   * 上会直接 ENOENT，在 macOS 上则要依赖用户 brew 装过。发现链已经把三处都覆盖了。
   */
  #resolveExecutable() {
    const found = findCloudflared(this.executable, this.env) || findCloudflared('auto', this.env);
    if (!found) {
      throw fail(4021, '主机未安装 cloudflared，无法开通固定地址', {
        detail: process.platform === 'win32'
          ? '在面板点「安装 cloudflared 并开启远程」自动下载，或手动安装后把目录加入 PATH'
          : '执行 `brew install cloudflared`，或设置 CLOUDFLARED_BIN 指向可执行文件',
      });
    }
    return found;
  }

  /** 公网当前 NS（查询失败就当没有：少一句提示不该让整条诊断崩掉）。 */
  async #publicNs() {
    try {
      return await resolveNs(this.baseDomain);
    } catch {
      return [];
    }
  }

  /**
   * 解析自检 + （失败时）zone 归因。
   *
   * 只把「解析不到」当作需要归因的信号：解析成功时多问一次 Cloudflare 只是浪费
   * 一次往返，而失败时那句笼统的「pending」正是把人带偏的根源——域名可能已经被
   * 另一个 Cloudflare 账号接管（zone moved），改 NS、重装、重启都不可能修好。
   */
  async #evaluate(hostname, tunnelId) {
    const verdict = evaluateDnsAnswer(await this.probe(hostname), tunnelId);
    if (verdict.ok || typeof this.zoneDiagnose !== 'function') {
      this._zone = null; // 通了就别留着上一次的故障结论
      return { verdict, zone: null };
    }
    let zone = null;
    try {
      zone = sanitizeZone(await this.zoneDiagnose({
        homeDir: this.homeDir,
        baseDomain: this.baseDomain,
        publicNs: await this.#publicNs(),
        dnsOk: false,
      }));
    } catch {
      zone = null; // 「不知道」比「猜一个」诚实
    }
    this._zone = zone;
    return { verdict, zone };
  }

  status() {
    const s = this.state;
    if (!s) return { kind: 'local', provisioned: false, hostname: null, url: null, tunnelId: null };
    return {
      kind: 'local',
      provisioned: true,
      hostname: s.hostname,
      url: `https://${s.hostname}`,
      tunnelId: s.tunnelId,
      port: s.port ?? null,
      // null = 还没验过（老状态文件）；false = 验过但公网没有——面板必须提示，别让人扫码扫到空气
      dnsOk: s.dnsOk ?? null,
      dnsCheckedAt: s.dnsCheckedAt ?? null,
      // 失败原因归到 zone 层（moved / pending / ns-mismatch / unresolved），
      // 面板据此给出**不同**的修法，而不是一律「等 NS 生效」。
      zone: s.zone ?? this._zone ?? null,
      warning: dnsWarningFor(s),
      createdAt: s.createdAt ?? null,
      updatedAt: s.updatedAt ?? null,
    };
  }

  /**
   * 面板「重新检测解析」：强制重探一次并写回状态，不做任何缓存短路。
   *
   * 为什么必须有这条路：dnsOk=false 是持久化结论，而面板在 false 时禁用了
   * 「开启远程」按钮——原来唯一的重探入口就在 ensure() 里，按钮一点就点不到，
   * 于是 NS 改好了也永远停在「解析异常」，只能删状态文件才恢复（自锁死）。
   */
  async recheckDns() {
    const s = this.state;
    if (!s?.hostname) return { provisioned: false, ok: false, tampered: false, warning: null, publicNs: [], zone: null };
    const { verdict, zone } = await this.#evaluate(s.hostname, s.tunnelId);
    const next = {
      ...s,
      dnsOk: verdict.ok,
      dnsTampered: verdict.tampered,
      dnsCheckedAt: new Date().toISOString(),
      zone,
    };
    this._state = next;
    writeState(this.stateFile, next);
    return {
      provisioned: true,
      hostname: next.hostname,
      ok: Boolean(verdict.ok),
      tampered: Boolean(verdict.tampered),
      expected: verdict.expected ?? null,
      target: verdict.target ?? null,
      warning: dnsWarningFor(next),
      checkedAt: next.dnsCheckedAt,
      zone,
    };
  }

  async #exec(args) {
    const { stdout, stderr } = await execFileAsync(this.#resolveExecutable(), args, {
      timeout: CLI_TIMEOUT_MS,
      maxBuffer: 4 * 1024 * 1024,
      env: process.env,
    });
    return `${stdout || ''}${stderr || ''}`;
  }

  async #assertLogin() {
    const cert = path.join(this.homeDir, '.cloudflared', 'cert.pem');
    if (!fs.existsSync(cert)) throw fail(4021, this.notConfiguredMessage, { detail: this.notConfiguredDetail });
  }

  /** 当前授权账号下的隧道列表；拿不到就返回 null（调用方必须当「未知」处理，不能当「没有」）。 */
  async #listTunnels() {
    let raw;
    try {
      raw = await this.run(['tunnel', 'list', '--output', 'json']);
    } catch {
      return null; // 老版本不支持 --output，或网络/凭据问题；交给 create 的报错去说明
    }
    const start = raw.indexOf('[');
    if (start < 0) return null;
    try {
      const list = JSON.parse(raw.slice(start));
      return Array.isArray(list) ? list : null;
    } catch {
      return null;
    }
  }

  async #findTunnelByName(label) {
    const list = await this.#listTunnels();
    if (!list) return null; // 老版本不支持 --output；交给 create 的报错去说明
    const hit = list.find((t) => isLiveTunnel(t) && t.name === label);
    return hit?.id ? { id: hit.id } : null;
  }

  /**
   * 这条 tunnel 是否还在当前授权账号里。
   * true / false 之外还有 null（查不到）——null 必须当作「可能还在」，别因为一次网络抖动
   * 就把用户正常的隧道判死重建。返回 undefined 表示根本没 id 可查。
   */
  async #tunnelInAccount(tunnelId) {
    if (!tunnelId) return undefined;
    const list = await this.#listTunnels();
    if (!list) return null;
    return list.some((t) => isLiveTunnel(t) && t.id === tunnelId);
  }

  async ensure({ port, force = false } = {}) {
    if (!Number.isInteger(port) || port <= 0) throw fail(4400, '开通隧道需要有效端口');
    // 授权账号可能变过（域名迁到另一个 Cloudflare 账号后重新 login 就是这种情况）：
    // 旧 tunnel 属于上一个账号，继续拿它的 id 去 route dns 只会得到 "tunnel not found"，
    // 或者更糟——静默写不进去却以为自己开通成功。真判定有两条线：
    //   1) 状态文件记了 account 且与当前 cert 不一致 → 确知换了账号；
    //   2) 没记（0.2.11 之前的状态文件没有这个字段）→ 直接问 Cloudflare 这条 tunnel
    //      还在不在当前账号（`tunnel list --output json`）。
    // 注意线 2) 只在「不知道归属」时才走：两种情况都清楚了还去拉子进程，会让面板每次
    // 点开通都多几百毫秒（tunnel-named 里「重复开通不再调 CLI」这条契约就是拦这个的）。
    // 账号变了就当新装：重建隧道、保留同一个子域（地址不变，用户不用重新记/重新扫码）。
    const account = readZoneCert({ homeDir: this.homeDir })?.accountId || null;
    let cached = this.state;
    let rebuild = false;
    if (cached?.tunnelId) {
      const knownMismatch = Boolean(cached.account && account && cached.account !== account);
      // 只有「当前证书能读出账号，但状态文件没记」才算归属未知。反过来若连证书都解析
      // 不出账号（cert.pem 被换过/格式不同），那属于凭据异常，此时去 list 再拿不到就
      // 判重建会变成反复重建隧道 —— 比保留旧 id 危险得多，所以这种情况直接信任缓存。
      const unknownOwner = Boolean(account) && !cached.account;
      const alive = knownMismatch
        ? false
        : unknownOwner ? await this.#tunnelInAccount(cached.tunnelId) : true;
      if (knownMismatch || alive === false) {
        this.log(knownMismatch
          ? `tunnel 授权账号已变更（${String(cached.account).slice(0, 8)}… → ${String(account).slice(0, 8)}…），重建隧道`
          : `tunnel ${String(cached.tunnelId).slice(0, 8)}… 不在当前授权账号里，重建隧道`);
        rebuild = true;
        cached = {
          ...cached,
          account,
          tunnelId: null,
          credentialsFile: null,
          configFile: null,
          dnsOk: null,
          dnsTampered: false,
          zone: null,
        };
      } else if (alive === true && cached.account !== account) {
        // 校验通过：把归属记下来。否则每次开通都因为「不知道归谁」再问一遍 Cloudflare，
        // 白白多一个子进程的延迟（这条路径就是给老状态文件补账的）。
        cached = { ...cached, account };
        this._state = cached;
        writeState(this.stateFile, cached);
      }
    }
    // 走完整开通：缓存里的 port/hostname 看着都可用，但它们描述的是上一个账号的隧道，
    // 跳过缓存才不会「解析通了就以为没事」。
    if (!force && !rebuild && cached?.hostname && cached.port === port) {
      // 与 BaseProvisioner 同策略：没确认过就现场验一次（含防篡改评估）
      if (cached.dnsOk !== true) {
        const { verdict, zone } = await this.#evaluate(cached.hostname, cached.tunnelId);
        const next = {
          ...cached,
          dnsOk: verdict.ok,
          dnsTampered: verdict.tampered,
          dnsCheckedAt: new Date().toISOString(),
          zone,
        };
        this._state = next;
        writeState(this.stateFile, next);
        return {
          hostname: next.hostname,
          url: `https://${next.hostname}`,
          tunnelId: next.tunnelId,
          created: false,
          changed: false,
          dnsOk: next.dnsOk,
          zone,
          warning: dnsWarningFor(next),
        };
      }
      return {
        hostname: cached.hostname,
        url: `https://${cached.hostname}`,
        tunnelId: cached.tunnelId,
        created: false,
        changed: false,
        dnsOk: cached.dnsOk ?? null,
        warning: dnsWarningFor(cached),
      };
    }
    await this.#assertLogin();

    // 端口顺延：tunnel 与 DNS 都不用动，只重写本地 ingress 配置。
    // 不走这一步就会为了换个端口重新 route dns（多余的一次 CF 写入）。
    if (!force && cached?.tunnelId && cached.hostname && cached.credentialsFile) {
      fs.mkdirSync(path.dirname(this.configFile), { recursive: true, mode: 0o700 });
      fs.writeFileSync(this.configFile, renderConfig({
        tunnelId: cached.tunnelId,
        credentialsFile: cached.credentialsFile,
        hostname: cached.hostname,
        port,
      }), { mode: 0o600 });
      const next = { ...cached, port, updatedAt: new Date().toISOString() };
      this._state = next;
      writeState(this.stateFile, next);
      return {
        hostname: next.hostname,
        url: `https://${next.hostname}`,
        tunnelId: next.tunnelId,
        created: false,
        changed: false,
        dnsOk: next.dnsOk ?? null,
        warning: dnsWarningFor(next),
      };
    }

    const installationId = cached?.installationId || crypto.randomBytes(16).toString('hex');
    const label = cached?.subdomain || deriveSubdomain(this.seed || installationId, { prefix: this.prefix });
    if (!isValidLabel(label)) throw fail(4400, `派生出的子域不合法：${label}`);
    const hostname = `${label}.${this.baseDomain}`;

    let tunnelId = cached?.tunnelId || null;
    let created = false;
    if (!tunnelId) {
      const found = await this.#findTunnelByName(label);
      if (found) {
        tunnelId = found.id;
      } else {
        const out = await this.run(['tunnel', 'create', label]);
        const m = UUID_PATTERN.exec(out);
        if (!m) throw fail(4500, 'cloudflared 没有返回 tunnel id', { detail: String(out).slice(-300) });
        tunnelId = m[1];
        created = true;
      }
    }

    const credentialsFile = path.join(this.homeDir, '.cloudflared', `${tunnelId}.json`);
    if (!fs.existsSync(credentialsFile)) {
      throw fail(4500, '找不到 tunnel 凭据文件', {
        detail: `期望在 ${path.basename(credentialsFile)}；重新执行 cloudflared tunnel create ${label}`,
      });
    }

    // 多机共用同一个 Cloudflare 账号时，`--overwrite-dns` 会**静默**把别人的地址抢走：
    // A 机本来能用，B 机一开通 A 机就断，两边面板却都显示「成功」。
    // 有凭据就先看这条 hostname 现在归谁，抢址直接报错，绝不静默覆盖。
    if (typeof this.ownerLookup === 'function') {
      let owner = null;
      try {
        owner = await this.ownerLookup({ homeDir: this.homeDir, baseDomain: this.baseDomain, hostname });
      } catch {
        owner = null; // 查不到归属时退回旧行为，别让诊断把开通卡死
      }
      if (owner && !cnameBelongsTo(owner, tunnelId)) {
        this.log(`tunnel 拒绝覆盖 ${hostname}：当前指向 ${owner}，本机隧道 ${tunnelId}`);
        throw fail(4021, `固定地址 ${hostname} 已被另一条隧道占用`, {
          detail: `该地址当前指向 ${owner}。通常是另一台电脑用了同一份安装标识（或状态文件被复制）。`
            + '本机已停止覆盖它：请在那台设备上重新开通以换一个地址，或先删掉这条 DNS 记录再重试。',
        });
      }
    }

    // --overwrite-dns：重复开通时把记录改到当前 tunnel，而不是报「已存在」
    try {
      await this.run(['tunnel', 'route', 'dns', '--overwrite-dns', label, hostname]);
    } catch (err) {
      throw fail(4500, `写入 DNS 失败：${String(err.message).split('\n')[0]}`, {
        detail: '确认 matrixboard.cn 在当前 Cloudflare 账号下，且登录时授权的就是它',
      });
    }

    fs.mkdirSync(path.dirname(this.configFile), { recursive: true, mode: 0o700 });
    fs.writeFileSync(this.configFile, renderConfig({ tunnelId, credentialsFile, hostname, port }), { mode: 0o600 });
    try { fs.chmodSync(this.configFile, 0o600); } catch { /* 已 0600 */ }

    const now = new Date().toISOString();
    // 开通即自检：DNS 写成功 ≠ 公网能解析（pending / moved zone 就是这么骗人的）；
    // CNAME 被改指到别的隧道同样不放行（防劫持评估见 dns-probe.evaluateDnsAnswer）
    const { verdict, zone } = await this.#evaluate(hostname, tunnelId);
    const warning = dnsWarningFor({ dnsOk: verdict.ok, dnsTampered: verdict.tampered, zone });
    if (verdict.tampered) {
      this.log(`tunnel 警告 固定地址解析被改指 ${hostname} → ${verdict.target}（期望 ${verdict.expected}），拒绝下发该地址`);
    } else if (verdict.ok) {
      this.log(`tunnel 固定地址已可解析 ${hostname}（${verdict.kind} ${verdict.records.join(',')}）`);
    } else {
      this.log(`tunnel 警告 固定地址写入成功但公网解析不到 ${hostname}`);
    }

    const next = {
      ...cached,
      installationId,
      // 记下这本证书属于哪个 Cloudflare 账号：下次若换了账号，能识别出「旧隧道不再可用」
      account: account || cached?.account || null,
      subdomain: label,
      hostname,
      tunnelId,
      credentialsFile,
      configFile: this.configFile,
      port,
      dnsOk: verdict.ok,
      dnsTampered: verdict.tampered,
      dnsCheckedAt: now,
      zone,
      createdAt: cached?.createdAt ?? now,
      updatedAt: now,
    };
    this._state = next;
    writeState(this.stateFile, next);
    this.log(`tunnel 固定地址就绪 ${hostname}（${created ? '新建' : '复用'}，本地管理型）`);
    return {
      hostname,
      url: `https://${hostname}`,
      tunnelId,
      created,
      changed: Boolean(cached && cached.hostname !== hostname),
      dnsOk: verdict.ok,
      zone,
      warning,
    };
  }

  async credential({ port }) {
    await this.ensure({ port });
    if (!this.state?.configFile) throw fail(4500, '隧道配置缺失，请重新开通固定地址');
    return { hostname: this.state.hostname, configFile: this.state.configFile };
  }
}
